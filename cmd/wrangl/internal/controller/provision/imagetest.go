package provision

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"time"
)

// ImageCheck is one line of the editor's checklist.
type ImageCheck struct {
	Name   string `json:"name"`
	OK     bool   `json:"ok"`
	Detail string `json:"detail,omitempty"`
}

// ImageTest is the outcome of launching one instance of an image to see whether a runner
// could bootstrap on it. Terminated is false only if the cleanup itself failed (the reaper
// then removes the instance: it carries the controller's tags).
type ImageTest struct {
	OK         bool         `json:"ok"`
	Checks     []ImageCheck `json:"checks"`
	InstanceID string       `json:"instance_id,omitempty"`
	Terminated bool         `json:"terminated"`
	Error      string       `json:"error,omitempty"`
}

// ProbeReport is what the probe script on the instance POSTs back.
type ProbeReport struct {
	Systemd string `json:"systemd"` // `systemctl is-system-running`, "" if systemd is not PID 1
	Curl    string `json:"curl"`    // path of curl
	HTTPS   string `json:"https"`   // "ok" or curl's error
	Distro  string `json:"distro,omitempty"`
}

var (
	probeURL   = regexp.MustCompile(`^https?://[A-Za-z0-9.\-:\[\]]+$`)
	probeToken = regexp.MustCompile(`^[A-Za-z0-9_\-]+$`)
)

// ProbeScript is the user-data of a test instance. It runs the same way the real bootstrap
// does (cloud-init user-data, as root), checks what that bootstrap depends on, and reports to
// <enrolURL>/imagecheck/<token>. Reaching the enrol port is itself the check of the VPC path.
// Having run at all proves cloud-init processed user-data. It powers off afterwards; the
// instance is set to terminate on shutdown.
func ProbeScript(enrollURL, token string) (string, error) {
	if !probeURL.MatchString(enrollURL) || !probeToken.MatchString(token) {
		return "", errors.New("unsafe probe parameters")
	}
	return `#!/bin/bash
# wrangl image test (generated by the controller)
SD=""
if [ -d /run/systemd/system ]; then SD=$(systemctl is-system-running 2>/dev/null | head -1); [ -n "$SD" ] || SD=unknown; fi
CURL=$(command -v curl || true)
HTTPS=$(curl -sS -m 15 -o /dev/null https://github.com 2>&1 | tr -d '"\\' | head -c 200)
[ -n "$HTTPS" ] || HTTPS=ok
DISTRO=$(. /etc/os-release 2>/dev/null && echo "$PRETTY_NAME" | tr -d '"\\')
BODY=$(printf '{"systemd":"%s","curl":"%s","https":"%s","distro":"%s"}' "$SD" "$CURL" "$HTTPS" "$DISTRO")
for i in 1 2 3 4 5 6; do
  curl -fsS -m 10 -X POST -H 'Content-Type: application/json' -d "$BODY" "` + enrollURL + `/imagecheck/` + token + `" && break
  sleep 5
done
shutdown -h now || poweroff
`, nil
}

// Evaluate turns a report into the checklist.
func (r ProbeReport) Evaluate() []ImageCheck {
	cs := []ImageCheck{
		{Name: "cloud-init ran user-data", OK: true, Detail: r.Distro},
		{Name: "reached the enrol port from the instance", OK: true},
	}
	sd := ImageCheck{Name: "systemd is running", OK: r.Systemd != "" && r.Systemd != "offline", Detail: r.Systemd}
	if r.Systemd == "" {
		sd.Detail = "systemd is not PID 1"
	}
	cs = append(cs, sd)
	cs = append(cs, ImageCheck{Name: "curl is installed", OK: r.Curl != "", Detail: r.Curl})
	cs = append(cs, ImageCheck{Name: "outbound HTTPS works", OK: r.HTTPS == "ok", Detail: func() string {
		if r.HTTPS == "ok" {
			return ""
		}
		return r.HTTPS
	}()})
	return cs
}

// testWait is how long a test instance gets to report.
var testWait = 4 * time.Minute

// TestImage launches one instance from s (whose UserData must be the ProbeScript for the
// token), waits for wait to return the instance's report, and always terminates it.
func (p *Provisioner) TestImage(ctx context.Context, s Spec, wait func(context.Context) (*ProbeReport, error)) (res ImageTest) {
	inst, err := p.Launch(ctx, s)
	if err != nil {
		res.Error = err.Error()
		res.Checks = []ImageCheck{{Name: "instance launched", Detail: err.Error()}}
		return res
	}
	res.InstanceID = inst.ID
	defer func() {
		cctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 30*time.Second)
		defer cancel()
		if err := p.Terminate(cctx, inst.ID); err != nil {
			res.Error = joinMsg(res.Error, "terminating "+inst.ID+": "+err.Error())
			return
		}
		res.Terminated = true
	}()
	wctx, cancel := context.WithTimeout(ctx, testWait)
	defer cancel()
	rep, err := wait(wctx)
	if err != nil || rep == nil {
		msg := fmt.Sprintf("no report within %s: cloud-init may not run user-data on this image, curl may be missing, or the enrol port is unreachable from the instance", testWait)
		res.Error = msg
		res.Checks = []ImageCheck{{Name: "instance launched", OK: true, Detail: inst.ID}, {Name: "cloud-init ran user-data and reached the enrol port", Detail: msg}}
		return res
	}
	res.Checks = append([]ImageCheck{{Name: "instance launched", OK: true, Detail: inst.ID}}, rep.Evaluate()...)
	res.OK = true
	for _, c := range res.Checks {
		res.OK = res.OK && c.OK
	}
	return res
}

func joinMsg(a, b string) string {
	if a == "" {
		return b
	}
	return a + "; " + b
}

// ParseProbeReport decodes a report body.
func ParseProbeReport(b []byte) (*ProbeReport, error) {
	var r ProbeReport
	if err := json.Unmarshal(b, &r); err != nil {
		return nil, err
	}
	return &r, nil
}
